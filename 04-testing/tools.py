 
# Import DuckDB, an embedded SQL database.
# DuckDB allows us to execute SQL queries directly from Python.
import duckdb


# ---------------------------------------------------------
# DATABASE CONNECTION
# ---------------------------------------------------------

# Connect to a local DuckDB database called taxi.db.
#
# If taxi.db already exists, DuckDB opens it.
# If it does not exist, DuckDB creates an empty database.
#
# 'con' is a connection object used to execute SQL queries.
con = duckdb.connect("data/taxi.db")


# ---------------------------------------------------------
# SQL TOOLS CLASS
# ---------------------------------------------------------

class SQLTools:
    """
    This class provides tools for our AI agent.

    The agent will use two methods:

    1. get_schema()
       Discover which columns exist in the database.

    2. run_sql(query)
       Execute SQL queries and return the results.

    These methods will later be registered as tools
    in our PydanticAI agent.
    """

    # -----------------------------------------------------
    # TOOL 1: GET DATABASE SCHEMA
    # -----------------------------------------------------

    def get_schema(self) -> str:
        """
        Return the column names and data types
        of the 'trips' table.

        Example output:

        passenger_count: BIGINT
        trip_distance: DOUBLE
        fare_amount: DOUBLE

        The return type 'str' means this method
        returns a Python string.
        """

        # Execute a SQL command to inspect the table.
        #
        # DESCRIBE trips returns information about
        # every column in the trips table.
        #
        # fetchall() retrieves all rows returned
        # by the SQL command.
        rows = con.execute("DESCRIBE trips").fetchall()

        # Each row contains information such as:
        # (column_name, column_type, null, key, default, extra)
        #
        # row[0] is the column name.
        # row[1] is the column data type.
        #
        # The f-string formats each column as:
        # "column_name: data_type"
        #
        # "\n".join(...) combines all formatted
        # columns into one string with line breaks.
        return "\n".join(
            f"{row[0]}: {row[1]}"
            for row in rows
        )

    # -----------------------------------------------------
    # TOOL 2: EXECUTE SQL QUERY
    # -----------------------------------------------------

    def run_sql(self, query: str) -> str:
        """
        Execute an SQL query against DuckDB.

        Parameters:
            query (str):
                The SQL query generated by our AI agent.

        Returns:
            str:
                Query results formatted as text,
                including column headers and up to 50 rows.

        Example query:

            SELECT AVG(trip_distance)
            FROM trips;

        Example result:

            avg(trip_distance)
            3.78
        """

        # Execute the SQL query received from the agent.
        #
        # Example:
        # query = "SELECT COUNT(*) FROM trips"
        #
        # con.execute(query) sends the query to DuckDB.
        result = con.execute(query)

        # Extract the column names from the query result.
        #
        # result.description contains metadata
        # about the returned columns.
        #
        # col[0] contains the name of each column.
        #
        # Example:
        # ["passenger_count", "trip_distance"]
        columns = [
            col[0] for col in result.description
        ]

        # Fetch a maximum of 50 rows.
        #
        # This prevents returning millions of records
        # to the AI agent.
        #
        # IMPORTANT:
        # The SQL query itself may process many rows.
        # fetchmany(50) only limits the returned rows.
        rows = result.fetchmany(50)

        # Create the first line of the output.
        #
        # The column names are separated by " | ".
        #
        # Example:
        # passenger_count | trip_distance
        output = [" | ".join(columns)]

        # Iterate over each returned database row.
        for row in rows:

            # Convert every value to a string.
            #
            # Example row:
            # (2, 3.5)
            #
            # Becomes:
            # "2 | 3.5"
            #
            # Append this formatted row to output.
            output.append(
                " | ".join(str(value) for value in row)
            )

        # Combine the header and all data rows
        # into a single string.
        #
        # "\n" adds a line break between rows.
        #
        # Example final output:
        #
        # passenger_count | trip_distance
        # 2 | 3.5
        # 1 | 4.2
        #
        # This string will be returned to the AI agent.
        return "\n".join(output)
